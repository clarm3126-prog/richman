def chip_labels():
    """index.html 의 칩 라벨을 함수별로 읽어 온다.

    ${...} 자리는 종목마다 값이 달라지는 부분이라 설명용으로 치환한다.
    예: '거래량 ${r.vol_ratio}배' -> '거래량 N배'
    """
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    out = {}
    for fn in re.finditer(r"function (mv\w*Chips|mom\w*Chips)\((.*?)\)\s*\{(.*?)\n\}", src, re.S):
        labels = re.findall(r"\[\s*[`'\"]([^`'\"]+)[`'\"]\s*,", fn.group(3))
        if labels:
            # ${...} 는 종목마다 달라지는 값이다. 설명서에서는 'N' 같은
            # 기호를 그대로 두면 읽는 사람이 무슨 뜻인지 모른다. 자리를
            # 비우고 조사만 남긴다. '거래량 ${r.vol_ratio}배' -> '거래량 몇 배'
            out[fn.group(1)] = [re.sub(r"\s+", " ", re.sub(r"\$\{[^}]+\}%?", "몇", l)).strip() for l in labels]
    return out


