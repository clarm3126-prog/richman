def _head(title, updated, one_line, detail):
    return ["# " + title, "",
            "> 화면을 그대로 옮긴 설명서입니다.",
            "> 숫자는 " + str(updated) + " 기준입니다.", "",
            "## 한 줄로 말하면", "",
            "**" + one_line + "**", "", detail, ""]


def _tail(notes, key):
    out = ["", "## 주의할 점", ""]
    out += ["- " + n for n in notes]
    out += ["", "**종목 추천이 아닙니다. 조건에 걸렸는지만 계산합니다.**",
            "", "태그: " + ", ".join(TAB_TAGS[key])]
    return out


